// Имя пользователя как ключ маршрутизации.
//
// Имена в аккаунтах регистрозависимы по написанию, но НЕ по смыслу: VMOZARK
// и vmozark — один человек. Пока сервер сравнивал их посимвольно, звонок на
// контакт, записанный в другом регистре, обрывался до начала: presence и
// VoIP-токен лежат под настоящим написанием, поиск шёл по введённому, оба
// промахивались, и человек выглядел «не в сети». Причём только в одну
// сторону — у второго абонента контакт был записан верно.
//
// Поэтому: показываем то написание, которое пришло, а ищем и сравниваем
// всегда через ukey.
function ukey(username) {
  return String(username || '').trim().toLowerCase();
}

module.exports = ukey;
module.exports.ukey = ukey;
